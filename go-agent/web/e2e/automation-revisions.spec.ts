import { expect, test, type Locator } from '@playwright/test'

async function keyboardSelect(select: Locator, label: string) {
  const options = await select.locator('option').allTextContents()
  const index = options.indexOf(label)
  expect(index).toBeGreaterThan(0)
  await select.focus()
  await select.press('Home')
  for (let i = 0; i < index; i++) await select.press('ArrowDown')
  await select.press('Enter')
  await expect(select.locator('option:checked')).toHaveText(label)
}
test('pending revisions retain an immutable old version and separate confirmation in narrow marked preview', async ({ page }) => {
  await page.goto('/app/')
  await page.getByLabel('用户名').fill('owner')
  await page.getByLabel('密码', { exact: true }).fill('fixture-password-123')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '家庭概况' })).toBeVisible()
  await page.goto('/app/automations?id=fixture_time')
  await expect(page.getByText('模拟预览 · 当前设备和自动化均为测试数据', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '修订建议', exact: true }).click()
  await expect(page.getByRole('group', { name: '动作目标' })).toBeVisible()
  await page.setViewportSize({ width: 305, height: 900 })
  await page.getByRole('button', { name: '保存修订并查看差异' }).click()
  await expect(page.getByLabel('触发时间', { exact: true })).toBeFocused()
  await page.getByLabel('触发时间', { exact: true }).fill('19:30')
  const target = page.getByRole('group', { name: '动作目标' })
  await keyboardSelect(target.getByLabel('房间', { exact: true }), '厨房')
  await keyboardSelect(target.getByLabel('设备', { exact: true }), '客厅三路开关')
  await keyboardSelect(target.getByLabel('实体', { exact: true }), '开关 2')
  const presence = page.getByRole('group', { name: '家庭占用条件' })
  await keyboardSelect(presence.getByLabel('房间', { exact: true }), '其他')
  await keyboardSelect(presence.getByLabel('设备', { exact: true }), '独立实体 · 全家有人（模拟聚合）')
  await keyboardSelect(presence.getByLabel('实体', { exact: true }), '全家有人（模拟聚合）')
  await keyboardSelect(page.getByLabel('有人在家时的状态', { exact: true }), '开启')
  const layout = await page.evaluate(() => ({ width: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }))
  expect(layout.scroll).toBeLessThanOrEqual(layout.width)
  await page.screenshot({ path: '../.tmp/a5-revision-editor-305.png', fullPage: true })
  await page.getByRole('button', { name: '保存修订并查看差异' }).click()
  await expect(page.getByRole('heading', { name: '版本差异', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '确认创建自动化', exact: true })).toBeEnabled()
  const version = new URL(page.url()).searchParams.get('id')
  expect(version).not.toBe('fixture_time')
  const list = await (await page.request.get('/api/console/v1/suggestions')).json()
  const old = list.suggestions.find((item: { id: string }) => item.id === 'fixture_time')
  const next = list.suggestions.find((item: { id: string }) => item.id === version)
  expect(old.status).toBe('superseded')
  expect(old.intent.at).toBe('18:00:00')
  expect(next.status).toBe('pending')
  expect(next.intent.at).toBe('19:30')
  expect(next.rule.actions[0].service).toBe('switch.turn_on')
  expect(next.evidence.sample_size).toBeNull()
  const identity = await (await page.request.get('/api/console/v1/auth/me')).json()
  const stale = await page.request.post('/api/console/v1/admin/suggestions/fixture_time/confirm', { headers: { Origin: 'http://127.0.0.1:18081', 'X-CSRF-Token': identity.csrf_token }, data: {} })
  expect(stale.status()).toBe(409)
  await page.screenshot({ path: '../.tmp/a5-revision-diff-305.png', fullPage: true })
  const after = await page.evaluate(() => ({ width: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }))
  expect(after.scroll).toBeLessThanOrEqual(after.width)
})
