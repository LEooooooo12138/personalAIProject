async function keyboardSelect(select:Locator,label:string) {
 const index=(await select.locator('option').allTextContents()).indexOf(label)
 expect(index).toBeGreaterThan(0)
 await select.focus();await select.press('Home')
 for(let i=0;i<index;i++)await select.press('ArrowDown')
 await select.press('Enter');await expect(select.locator('option:checked')).toHaveText(label)
}
