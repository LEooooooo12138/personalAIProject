import { expect, test } from '@playwright/test'
import fs from 'node:fs/promises'
import path from 'node:path'

test('installed diagnostics preserve unknown and stale facts without HA writes at narrow width', async ({ page }) => {
 test.skip(process.env.CONSOLE_AUTOMATION_LIFECYCLE !== '1', 'Requires the opt-in local lifecycle fixture')
 const root = process.env.CONSOLE_FIXTURE_TEMP_ROOT
 if (!root || !path.isAbsolute(root)) throw new Error('Runner-owned fixture root required')
 const realRoot = await fs.realpath(root)
 expect(realRoot).toBe(path.resolve(root))
 const descriptorPath = path.join(realRoot, 'automation-lifecycle.json')
 expect((await fs.lstat(descriptorPath)).isSymbolicLink()).toBe(false)
 const descriptor = JSON.parse(await fs.readFile(descriptorPath,'utf8'))
 expect(descriptor.schema_version).toBe(1)
 expect(descriptor.url).toMatch(/^http:\/\/127\.0\.0\.1:\d+$/)
 expect(descriptor.capability).toMatch(/^[a-f0-9]{64}$/)
 async function control(route:string, mode?:Record<string,string>) {
  const response=await fetch(descriptor.url+route,{method:mode?'PUT':'GET',headers:{Authorization:`Bearer ${descriptor.capability}`,...(mode?{'Content-Type':'application/json'}:{})},...(mode?{body:JSON.stringify(mode)}:{})})
  expect(response.ok).toBe(true)
  return response.json()
 }
 await page.goto('/app/')
 await page.getByLabel('用户名').fill('owner')
 await page.getByLabel('密码',{exact:true}).fill('fixture-password-123')
 await page.getByRole('button',{name:'登录',exact:true}).click()
 await expect(page.getByRole('heading',{name:'家庭概况'})).toBeVisible()
 await page.goto('/app/automations?id=fixture_time')
 await page.getByRole('button',{name:'补齐有人在家条件'}).click()
 await page.getByLabel('房间',{exact:true}).selectOption({label:'其他'})
 await page.getByLabel('设备',{exact:true}).selectOption({label:'独立实体 · 全家有人（模拟聚合）'})
 await page.getByLabel('实体',{exact:true}).selectOption('group.family_home')
 await page.getByLabel('有人在家时的状态').selectOption('on')
 await page.getByRole('button',{name:'保存绑定并查看新版本'}).click()
 await expect(page).toHaveURL(url=>Boolean(url.searchParams.get('id'))&&url.searchParams.get('id')!=='fixture_time')
 await page.getByRole('button',{name:'确认创建自动化',exact:true}).click()
 await expect(page.getByText('已核实安装并归档',{exact:true})).toBeVisible()
 const before=(await control('/state')).writes
 await control('/mode',{state:'off',trace:'forbidden'})
 await page.goto('/app/automations')
 await page.getByRole('button',{name:/^已安装/}).click()
 const diagnose=page.getByRole('button',{name:/^只读诊断：/})
 await expect(diagnose).toHaveCount(1)
 await diagnose.focus();await diagnose.press('Enter')
 await expect(page.getByText(/已停用（记录中的观察）/)).toBeVisible()
 await expect(page.getByText('部分无法核对',{exact:true})).toBeVisible()
 await expect(page.getByText('已检查项目正常',{exact:true})).toHaveCount(0)
 await expect(page.locator('body')).not.toContainText('LIFECYCLE_PRIVATE')
 const observed=await page.getByLabel(/^记录中的观察时间：/).getAttribute('datetime')
 expect(observed).toBeTruthy()
 const native=page.getByRole('link',{name:'在 Home Assistant 中查看'})
 await expect(native).toHaveAttribute('href',/^http:\/\/127\.0\.0\.1:\d+\/config\/automation\/dashboard$/)
 await expect(native).toHaveAttribute('rel','noopener noreferrer')
 await page.setViewportSize({width:305,height:900})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth)).toBe(true)
 await page.screenshot({path:path.resolve('../.tmp/a10-diagnostics-305.png'),fullPage:true})
 // A bounded corrupt diagnostic record makes the real gateway read fail. The
 // SharedWorker transport and store/error projection remain unmocked.
 const children=(await fs.readdir(realRoot)).filter(name=>name.startsWith('console-fixture-'))
 expect(children).toHaveLength(1)
 const diagnostics=await fs.realpath(path.join(realRoot,children[0],'agent','smart-home','diagnostics'))
 expect(path.relative(realRoot,diagnostics).startsWith('..')).toBe(false)
 const files=(await fs.readdir(diagnostics)).filter(name=>/^[a-f0-9]{64}\.json$/.test(name))
 expect(files).toHaveLength(1)
 const evidenceFile=path.join(diagnostics,files[0])
 expect((await fs.lstat(evidenceFile)).isSymbolicLink()).toBe(false)
 expect(await fs.realpath(evidenceFile)).toBe(evidenceFile)
 const originalEvidence=await fs.readFile(evidenceFile)
 await fs.writeFile(evidenceFile,'{')
 await page.getByRole('button',{name:'刷新诊断列表'}).click()
 await expect(page.getByText(/读取失败，保留上次观察/)).toBeVisible()
 await expect(page.getByLabel(/^记录中的观察时间：/)).toHaveAttribute('datetime',observed!)
 await expect(page.getByText(/已过期，暂无法更新核对/)).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth)).toBe(true)
 await page.screenshot({path:path.resolve('../.tmp/a10-diagnostics-stale-305.png'),fullPage:true})
 expect((await control('/state')).writes).toEqual(before)
 expect(await fs.realpath(evidenceFile)).toBe(evidenceFile)
 expect(await fs.readFile(evidenceFile,'utf8')).toBe('{')
 await fs.writeFile(evidenceFile,originalEvidence)
 expect((await fs.readFile(evidenceFile)).equals(originalEvidence)).toBe(true)
})
