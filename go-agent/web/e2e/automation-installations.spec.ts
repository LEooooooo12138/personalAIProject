import { expect, test } from '@playwright/test'
import fs from 'node:fs/promises'
import path from 'node:path'

// Faults are injected only into the runner-created disposable local store.
// All UI transport, handlers, Manager and HTTP/WS HA observations remain real.
test('durable unknown blocks replay and read-only reconciliation separates archive failure', async ({ page }) => {
  await page.goto('/app/')
  await page.getByLabel('用户名').fill('owner')
  await page.getByLabel('密码', { exact: true }).fill('fixture-password-123')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '家庭概况' })).toBeVisible()
  await page.goto('/app/automations?id=fixture_time')
  await page.getByRole('button', { name: '补齐有人在家条件' }).click()
  await page.getByLabel('房间', { exact: true }).selectOption({ label: '其他' })
  await page.getByLabel('设备', { exact: true }).selectOption({ label: '独立实体 · 全家有人（模拟聚合）' })
  await page.getByLabel('实体', { exact: true }).selectOption('group.family_home')
  await page.getByLabel('有人在家时的状态').selectOption('on')
  await page.getByRole('button', { name: '保存绑定并查看新版本' }).click()
  await expect(page).toHaveURL(url => Boolean(url.searchParams.get('id')) && url.searchParams.get('id') !== 'fixture_time')
  const id = new URL(page.url()).searchParams.get('id')!
  await page.getByRole('button', { name: '确认创建自动化' }).click()
  await expect(page.getByText('已核实安装并归档', { exact: true })).toBeVisible()

  const suppliedRoot = process.env.CONSOLE_FIXTURE_TEMP_ROOT
  if (!suppliedRoot || !path.isAbsolute(suppliedRoot)) throw new Error('Runner-owned fixture root required')
  const root = await fs.realpath(suppliedRoot)
  expect(root).toBe(path.resolve(suppliedRoot))
  expect((await fs.lstat(root)).isSymbolicLink()).toBe(false)
  const children = (await fs.readdir(root)).filter(name => name.startsWith('console-fixture-'))
  expect(children).toHaveLength(1)
  const rules = await fs.realpath(path.join(root, children[0], 'agent', 'smart-home', 'rules'))
  expect(path.relative(root, rules).startsWith('..')).toBe(false)
  async function owned(name: string) {
    const file = path.join(rules, name)
    expect(path.dirname(file)).toBe(rules)
    expect((await fs.lstat(file)).isSymbolicLink()).toBe(false)
    expect(await fs.realpath(file)).toBe(file)
    return file
  }
  const journalPath = await owned('install-state.json')
  const suggestionsPath = await owned('suggestions.json')
  const archivePath = await owned(id + '.md')
  const state = JSON.parse(await fs.readFile(journalPath, 'utf8'))
  const op = state.operations.find((item: { suggestion_id: string }) => item.suggestion_id === id)
  expect(op.own_attempt).toBe(true)
  op.status = 'unknown'; op.phase = 'reload'; op.reload.status = 'unknown'
  op.observation = null; op.archive = { status: 'not_ready' }; op.error_code = 'install_reload_unknown'
  const suggestions = JSON.parse(await fs.readFile(suggestionsPath, 'utf8'))
  const suggestion = suggestions.suggestions.find((item: { id: string }) => item.id === id)
  suggestion.status = 'pending'
  suggestions.suggestions.push({ ...suggestion, id: 'a7_legacy_history', status: 'confirmed' })
  await fs.writeFile(journalPath, JSON.stringify(state))
  await fs.writeFile(suggestionsPath, JSON.stringify(suggestions))
  await fs.unlink(archivePath)
  await fs.mkdir(archivePath)
  const originalCreate = JSON.stringify(op.create)
  const originalReload = JSON.stringify(op.reload)
  await page.setViewportSize({ width: 305, height: 900 })
  await page.reload()
  await expect(page.getByText('配置已保存，加载结果待核对', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '确认创建自动化' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '保存绑定并查看新版本' })).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
  const evidence = path.resolve('../.tmp')
  await page.screenshot({ path: path.join(evidence, 'a7-install-unknown-305.png'), fullPage: true })
  const reconcile = page.getByRole('button', { name: '只读核对安装状态', exact: true })
  await reconcile.focus()
  await reconcile.press('Enter')
  await expect(page.getByText('安装已核实，本地归档待完成', { exact: true })).toBeVisible()
  await expect(page.getByText('本地归档待完成', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
  await page.screenshot({ path: path.join(evidence, 'a7-install-archive-pending-305.png'), fullPage: true })
  expect((await fs.lstat(await owned(id + '.md'))).isDirectory()).toBe(true)
  await fs.rmdir(archivePath)
  await reconcile.click()
  await expect(page.getByText('已核实安装并归档', { exact: true })).toBeVisible()
  const recovered = JSON.parse(await fs.readFile(journalPath, 'utf8'))
  expect(recovered.operations).toHaveLength(state.operations.length)
  const finalOp = recovered.operations.find((item: { id: string }) => item.id === op.id)
  expect(JSON.stringify(finalOp.create)).toBe(originalCreate)
  expect(JSON.stringify(finalOp.reload)).toBe(originalReload)
  expect(finalOp.expected_digest).toBe(op.expected_digest)
  expect(finalOp.status).toBe('confirmed')
  expect(finalOp.archive.status).toBe('complete')
  await page.goto('/app/automations?id=a7_legacy_history')
  await expect(page.getByText('历史安装记录，当前归属与加载未核实', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '确认创建自动化' })).toHaveCount(0)
  await page.screenshot({ path: path.join(evidence, 'a7-install-legacy-305.png'), fullPage: true })
})
